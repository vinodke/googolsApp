using Googols.Domain.Common;

namespace Googols.Domain.Assessment;

public enum QuestionSource
{
    Manual = 0,
    AiDraft = 1,   // generated by the AI from lesson text; always starts as Draft and needs human review
}

/// <summary>
/// A multiple-choice question in a chapter's question bank. Only Published questions are ever shown to students.
/// Options are stored as a JSON array of strings; the correct answer never leaves the server until a quiz is submitted.
/// </summary>
public class Question : Entity, ISoftDeletable
{
    public const int MinOptions = 2;
    public const int MaxOptions = 6;

    public Guid ChapterId { get; set; }
    public required string Prompt { get; set; }
    public required string OptionsJson { get; set; }
    public int CorrectIndex { get; set; }
    public string? Explanation { get; set; }
    public int Difficulty { get; set; } = 2;            // 1 easy · 2 medium · 3 hard
    public string Language { get; set; } = LanguageCodes.English;
    public QuestionSource Source { get; set; } = QuestionSource.Manual;
    public PublicationStatus Status { get; set; } = PublicationStatus.Draft;
    public DateTime? ArchivedAtUtc { get; set; }
}

/// <summary>
/// One sitting of a chapter quiz. The question set and the student's answers are frozen in the attempt,
/// so later edits to the bank don't change past results.
/// </summary>
public class QuizAttempt : Entity
{
    public const int QuestionsPerQuiz = 10;
    public static readonly TimeSpan MaxDuration = TimeSpan.FromHours(3);

    public Guid StudentId { get; set; }
    public Guid ChapterId { get; set; }
    public required string QuestionIdsJson { get; set; }
    public string? AnswersJson { get; set; }
    public DateTime StartedAtUtc { get; set; }
    public DateTime? SubmittedAtUtc { get; set; }
    public int Score { get; set; }
    public int Total { get; set; }
    public double Percent { get; set; }
}
