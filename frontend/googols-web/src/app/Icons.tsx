/** Circular progress (0–1) with a gradient stroke. */
export function ProgressRing({ value, size = 132, stroke = 12, children }: { value: number; size?: number; stroke?: number; children?: ReactNode }) {
  const r = (size - stroke) / 2
  const c = 2 * Math.PI * r
  const v = Math.max(0, Math.min(1, value))
  return (
    <div className="ring" style={{ width: size, height: size }}>
      <svg width={size} height={size} aria-hidden="true">
        <defs>
          <linearGradient id="ringGradient" x1="0" y1="0" x2="1" y2="1">
            <stop offset="0%" stopColor="#4f46e5" /><stop offset="60%" stopColor="#8b5cf6" /><stop offset="100%" stopColor="#06b6d4" />
          </linearGradient>
        </defs>
        <circle className="ring-track" cx={size / 2} cy={size / 2} r={r} fill="none" strokeWidth={stroke} />
        <circle className="ring-fill" cx={size / 2} cy={size / 2} r={r} fill="none" strokeWidth={stroke}
          strokeDasharray={c} strokeDashoffset={c * (1 - v)} />
      </svg>
      <div className="ring-label">{children}</div>
    </div>
  )
}

const TINTS = ['indigo', 'teal', 'amber', 'rose', 'sky', 'lime'] as const
/** Stable colour per item, so a subject keeps its colour everywhere. */
export function tintFor(key: string) {
  let h = 0
  for (const ch of key) h = (h * 31 + ch.charCodeAt(0)) >>> 0
  return `tint-${TINTS[h % TINTS.length]}`
}
